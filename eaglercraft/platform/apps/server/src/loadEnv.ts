import { existsSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Load `platform/.env` into process.env (does not overwrite vars already set).
 * No-op when the file or a variable is already present, so Docker/CI env wins.
 */
export function loadEnvIfPresent(): void {
  const here = dirname(fileURLToPath(import.meta.url)); // src or dist
  const platformRoot = resolve(here, "..", "..", "..");
  const file = resolve(platformRoot, ".env");
  if (!existsSync(file)) return;
  for (const rawLine of readFileSync(file, "utf8").split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq < 0) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined) process.env[key] = value;
  }
}